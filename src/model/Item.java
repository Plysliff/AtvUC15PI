
package model;

public class Item {
    
    int id;
    int Personagens_id;
    String item;
    String tipo;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getPersonagens_id() {
        return Personagens_id;
    }

    public void setPersonagens_id(int Personagens_id) {
        this.Personagens_id = Personagens_id;
    }

    public String getItem() {
        return item;
    }

    public void setItem(String item) {
        this.item = item;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }
    
    
}
